"""
test_phase1.py – Comprehensive validation of Phase 1 requirements:
1. Genuine HSR Layout OSM extract exists and is valid.
2. SUMO netconvert produces a valid net.xml with real intersections and TLS.
3. 4-intersection cluster is properly selected and documented with real street names and coordinates.
4. K=4 signal plans per junction are defined over actual SUMO phases.
5. Connectivity between cluster junctions is verified.
6. Network sketch image exists.
7. SUMO loads the network cleanly via TraCI.
"""

import json
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "src"))
SUMO_DIR = PROJECT_ROOT / "sumo_files"
SUMO_EXE = Path(os.environ.get("SUMO_HOME", r"C:\Program Files (x86)\SUMO")) / "bin" / "sumo.exe"


def test_osm_extract_genuine():
    """Verify that hsr_raw.osm is a genuine OpenStreetMap XML file."""
    osm = SUMO_DIR / "hsr_raw.osm"
    assert osm.exists(), f"OSM file missing: {osm}"
    # Genuine extract for HSR layout is multiple megabytes (>500 KB at minimum)
    assert osm.stat().st_size > 500_000, f"OSM file too small ({osm.stat().st_size} bytes)"
    
    # Read sample and verify OSM XML structure
    with open(osm, "rb") as f:
        header = f.read(500)
    assert b"<osm" in header, "File does not start with OSM XML declaration"
    assert b"SYNTHETIC" not in header, "File contains synthetic marker; must be genuine OSM"


def test_net_xml_valid():
    """Verify that hsr.net.xml was generated by netconvert and has real junctions and TLS."""
    net = SUMO_DIR / "hsr.net.xml"
    assert net.exists(), f"Net XML missing: {net}"
    assert net.stat().st_size > 1_000_000, f"Net XML suspiciously small ({net.stat().st_size} bytes)"

    root = ET.parse(net).getroot()
    junctions = [j for j in root.findall(".//junction") if not j.get("id", "").startswith(":")]
    tls_list = root.findall(".//tlLogic")
    
    # In genuine HSR extract, there are hundreds of junctions and multiple TLS programs
    assert len(junctions) >= 100, f"Expected >= 100 junctions in HSR layout, found {len(junctions)}"
    assert len(tls_list) >= 4, f"Expected >= 4 TLS programs in HSR layout, found {len(tls_list)}"


def test_cluster_config():
    """Verify cluster_config.json contains 4 verified intersections and K=4 plans."""
    cfg_p = SUMO_DIR / "cluster_config.json"
    assert cfg_p.exists(), f"cluster_config.json missing: {cfg_p}"
    
    cfg = json.loads(cfg_p.read_text(encoding="utf-8"))
    assert cfg.get("network_source") == "OpenStreetMap_official_API"
    
    cluster_tls = cfg.get("cluster_tls_ids", [])
    assert len(cluster_tls) == 4, f"Expected 4 cluster TLS, found {len(cluster_tls)}"
    
    plans = cfg.get("plans", {})
    for tid in cluster_tls:
        assert tid in plans, f"No plans defined for TLS {tid}"
        j_plans = plans[tid]
        assert len(j_plans) == 4, f"Expected K=4 plans for {tid}, got {len(j_plans)}"
        for idx, p in enumerate(j_plans):
            assert p["plan_id"] == idx
            assert len(p["phases"]) >= 2, f"Plan {idx} for {tid} has fewer than 2 phases"
            for phase in p["phases"]:
                assert "duration" in phase and phase["duration"] > 0
                assert "state" in phase and len(phase["state"]) > 0


def test_connectivity():
    """Verify road connectivity between cluster junctions."""
    cfg_p = SUMO_DIR / "cluster_config.json"
    cfg = json.loads(cfg_p.read_text(encoding="utf-8"))
    connectivity = cfg.get("connectivity", [])
    assert len(connectivity) >= 4, f"Expected at least 4 directed connected pairs, got {len(connectivity)}"


def test_sketch_exists():
    """Verify that net_sketch.png was created and has non-trivial size."""
    sketch = SUMO_DIR / "net_sketch.png"
    assert sketch.exists(), f"Sketch image missing: {sketch}"
    assert sketch.stat().st_size > 10_000, "Sketch image suspiciously small"


def test_traci_load_simulation():
    """Verify that SUMO can start with hsr.net.xml and TraCI can access all 4 TLS."""
    import traci
    net = SUMO_DIR / "hsr.net.xml"
    cfg_p = SUMO_DIR / "cluster_config.json"
    cfg = json.loads(cfg_p.read_text(encoding="utf-8"))
    cluster_tls = cfg.get("cluster_tls_ids", [])

    cmd = [str(SUMO_EXE), "-n", str(net), "--no-step-log", "true", "--no-warnings", "true"]
    try:
        traci.start(cmd)
        active_tls = traci.trafficlight.getIDList()
        for tid in cluster_tls:
            assert tid in active_tls, f"TLS {tid} not active in SUMO TraCI"
            state = traci.trafficlight.getRedYellowGreenState(tid)
            assert len(state) > 0, f"Empty state for TLS {tid}"
        traci.close()
    except Exception as e:
        try:
            traci.close()
        except:
            pass
        pytest.fail(f"TraCI failed to load network: {e}")
